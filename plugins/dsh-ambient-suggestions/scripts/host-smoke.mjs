import fs from 'node:fs';
import { createRequire } from 'node:module';
import { pathToFileURL, fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
const anchor = process.env.DSH_TEST_ANCHOR;
if (!anchor) throw new Error('Set DSH_TEST_ANCHOR to the installed host package.json.');
const requireHost = createRequire(anchor);
const { Context } = await import(requireHost.resolve('@deepseek-ai/cordis'));
const root = fileURLToPath(new URL('../src/', import.meta.url));
const rebind = (code, names) => names.reduce((text, name) => text.replace(`'${name}'`, JSON.stringify(pathToFileURL(requireHost.resolve(name)).href)), code);
const rpc = rebind(fs.readFileSync(root + 'rpc.js', 'utf8'), ['zod', '@deepseek-ai/dsh-typert-protocol/remote-info']);
const rpcURL = 'data:text/javascript;base64,' + Buffer.from(rpc).toString('base64');
let source = rebind(fs.readFileSync(root + 'index.js', 'utf8'), ['@deepseek-ai/schemastery', '@deepseek-ai/dsh-typert-protocol']);
source = source.replace("'./rpc.js'", JSON.stringify(rpcURL)).replace("'./engine.js'", JSON.stringify(pathToFileURL(root + 'engine.js').href));
const plugin = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
const ctx = new Context();
let descriptors;
ctx.provide('typert', { register(info) { descriptors = info.invocations; } });
ctx.provide('llm', { listProviders: () => [{ id: 'test', name: 'Test provider' }], listModels: async () => [{ id: 'test-model', name: 'Test model' }] });
ctx.provide('sessionController', {});
ctx.provide('sessionProjections', {});
ctx.provide('agentDefaultModel', {});
const fiber = ctx.plugin(plugin, { model: '', timeoutMs: 8000 });
await new Promise(resolve => setTimeout(resolve, 30));
const service = ctx.get('ambientSuggestions');
assert.ok(service);
assert.equal(descriptors.length, 2);
assert.equal(service.typertRemote.serviceKey, 'ambientSuggestions');
const preferences = await service.preferences(new AbortController().signal);
assert.equal(preferences.model, '');
assert.equal(preferences.groups[0].models[0].id, 'test-model');
console.log(JSON.stringify({ serviceRegistered: true, strictMethods: descriptors.length, modelCatalog: true, volatileConfig: typeof service.config.model.get === 'function' }));
await fiber.dispose();
